"""Fail-closed, local-only operator consent for the SCHNAPPER Ollama pilot.

The local service cannot manufacture this approval. Approval must be a separately
prepared, short-lived 0600 file for exactly one currently open task. This is a
same-user operational safeguard, NOT cryptographic proof of human identity.
No approval file is shipped or generated by the application.
"""
import datetime as dt
import json
import os
import pathlib
import re
import stat

from ki import KINichtVerfuegbar

TEAM = pathlib.Path(__file__).resolve().parent
WORK = TEAM / "work"
APPROVAL = WORK / "operator_approval.json"
TASKS = TEAM / "tasks.json"
STOP = WORK / "STOP"
DENIED = "BLOCKIERT: explizite lokale Betreiberfreigabe oder passende offene Aufgabe fehlt."


def _read_json(path, max_bytes, private=False):
    """Read bounded local JSON, no symlinks; never return untrusted diagnostics."""
    try:
        if path.is_symlink() or not hasattr(os, "O_NOFOLLOW"):
            raise ValueError("unsafe platform or link")
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise ValueError("not an ordinary file")
            if private:
                if (stat.S_IMODE(info.st_mode) & 0o077) != 0:
                    raise ValueError("operator approval is readable by others")
                if hasattr(os, "getuid") and info.st_uid != os.getuid():
                    raise ValueError("operator approval owner mismatch")
            if info.st_size > max_bytes:
                raise ValueError("oversized approval/tasks")
            with os.fdopen(fd, "rb") as f:
                fd = -1
                payload = f.read(max_bytes + 1)
            if len(payload) > max_bytes:
                raise ValueError("oversized approval/tasks")
            return json.loads(payload)
        finally:
            if fd >= 0:
                os.close(fd)
    except (OSError, ValueError, UnicodeError, TypeError) as exc:
        raise KINichtVerfuegbar(DENIED) from exc


def pruefe_freigabe(now=None):
    """Re-check immediately before EVERY local model request; never cache."""
    if WORK.is_symlink() or WORK.resolve() != (TEAM / "work").absolute():
        raise KINichtVerfuegbar(DENIED)
    if STOP.exists() or STOP.is_symlink():
        raise KINichtVerfuegbar("BLOCKIERT: Betreiber-Not-Aus aktiv.")
    approval = _read_json(APPROVAL, 4096, private=True)
    tasks = _read_json(TASKS, 100_000)
    if not isinstance(approval, dict) or not isinstance(tasks, dict):
        raise KINichtVerfuegbar(DENIED)
    task_id = approval.get("task_id")
    if (approval.get("approved") is not True
            or approval.get("scope") != "LOCAL_OLLAMA_ONLY"
            or not isinstance(task_id, str)
            or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", task_id)):
        raise KINichtVerfuegbar(DENIED)
    try:
        expiration = dt.datetime.fromisoformat(approval["expires_at_utc"].replace("Z", "+00:00"))
    except (KeyError, AttributeError, TypeError, ValueError) as exc:
        raise KINichtVerfuegbar(DENIED) from exc
    if expiration.tzinfo is None or expiration.utcoffset() != dt.timedelta(0):
        raise KINichtVerfuegbar(DENIED)
    current = now or dt.datetime.now(dt.timezone.utc)
    if current.tzinfo is None or current.utcoffset() != dt.timedelta(0):
        raise KINichtVerfuegbar(DENIED)
    if not dt.timedelta(0) < expiration - current <= dt.timedelta(hours=1):
        raise KINichtVerfuegbar(DENIED)
    if not isinstance(tasks.get("tasks"), list):
        raise KINichtVerfuegbar(DENIED)
    opened = [t.get("id") for t in tasks["tasks"]
              if isinstance(t, dict) and t.get("status") == "open"]
    if opened != [task_id]:
        raise KINichtVerfuegbar(DENIED)
    return task_id
